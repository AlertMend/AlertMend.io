import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { discoverStaticBlogSlugs } from './discover-static-blogs.mjs'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')

const slugs = discoverStaticBlogSlugs()

const slugsMjs = `/** Auto-generated by scripts/generate-static-blog-registry.mjs — do not edit manually */
export const STATIC_BLOG_SLUGS = ${JSON.stringify(slugs)}

export function isStaticBlogSlug(slug) {
  return STATIC_BLOG_SLUGS.includes(slug)
}
`

const slugsTs = `/** Auto-generated by scripts/generate-static-blog-registry.mjs — do not edit manually */
export const STATIC_BLOG_SLUGS = new Set(${JSON.stringify(slugs)})

export function isStaticBlog(slug: string): boolean {
  return STATIC_BLOG_SLUGS.has(slug)
}

/** URL path for any blog post (static HTML or React markdown). */
export function getBlogPostPath(slug: string): string {
  return '/blog/' + slug
}
`

fs.writeFileSync(path.join(root, 'scripts/static-blog-slugs.mjs'), slugsMjs)
fs.writeFileSync(path.join(root, 'src/utils/staticBlogRegistry.ts'), slugsTs)

console.log(`✓ Static blog registry: ${slugs.length} rich post(s)`)
if (slugs.length > 0) {
  slugs.forEach((s) => console.log(`   · ${s}`))
}
